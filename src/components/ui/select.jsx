// Mobile Drawer version of SelectContent
function SelectContentMobile({ children, label }) {
  const [open, setOpen] = React.useState(false);
  // We can't intercept Radix open state from outside here easily,
  // so we forward to a portal-based drawer by listening to the parent Select open event.
  // Instead, wrap items in a scrollable list inside the Drawer.
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        className={cn(
          "relative z-50 max-h-96 min-w-[8rem] overflow-hidden rounded-t-2xl border bg-popover text-popover-foreground shadow-md",
          "data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0",
          "data-[state=open]:slide-in-from-bottom-4",
          "fixed bottom-0 left-0 right-0 w-full rounded-t-2xl"
        )}
        position="item-aligned"
      >
        <div className="w-12 h-1.5 bg-muted rounded-full mx-auto mt-3 mb-2" />
        {label && <p className="text-xs text-muted-foreground px-4 pb-2 font-medium uppercase tracking-wide">{label}</p>}
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport className="p-2 pb-6">
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  );
}

const SelectContent = React.forwardRef(({ className, children, position = "popper", label, ...props }, ref) => {
  const isMobile = useIsMobile();

  if (isMobile) {
    return (
      <SelectPrimitive.Portal>
        <SelectPrimitive.Content
          ref={ref}
          className={cn(
            "relative z-50 max-h-[60vh] min-w-[8rem] overflow-hidden",
            "bg-popover text-popover-foreground shadow-xl",
            "data-[state=open]:animate-in data-[state=closed]:animate-out",
            "data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0",
            "data-[state=open]:slide-in-from-bottom-4 data-[state=closed]:slide-out-to-bottom-4",
            "fixed bottom-0 left-0 right-0 w-full rounded-t-2xl border-t border-border",
            className
          )}
          position="item-aligned"
          {...props}
        >
          <div className="w-10 h-1 bg-muted-foreground/20 rounded-full mx-auto mt-3 mb-1 flex-shrink-0" />
          {label && (
            <p className="text-xs text-muted-foreground px-4 py-2 font-medium uppercase tracking-wide border-b border-border">
              {label}
            </p>
          )}
          <SelectScrollUpButton />
          <SelectPrimitive.Viewport className="p-2 pb-8">
            {children}
          </SelectPrimitive.Viewport>
          <SelectScrollDownButton />
        </SelectPrimitive.Content>
      </SelectPrimitive.Portal>
    );
  }

  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        ref={ref}
        className={cn(
          "relative z-50 max-h-96 min-w-[8rem] overflow-hidden rounded-md border bg-popover text-popover-foreground shadow-md data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2",
          position === "popper" &&
            "data-[side=bottom]:translate-y-1 data-[side=left]:-translate-x-1 data-[side=right]:translate-x-1 data-[side=top]:-translate-y-1",
          className
        )}
        position={position}
        {...props}>
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport
          className={cn("p-1", position === "popper" &&
            "h-[var(--radix-select-trigger-height)] w-full min-w-[var(--radix-select-trigger-width)]")}>
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  );
})
SelectContent.displayName = SelectPrimitive.Content.displayName

